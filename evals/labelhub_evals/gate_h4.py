"""ADR-021 §6: does H4 (precedents) beat H3 (calibrated policy without precedents)?

Both runs are scored with the H3 method (ADR-020 §2, 2-fold held-out policy pick), at the same
escalation budget. Replay only: no model calls.

PASS iff
1. held-out bad exports / 1000 at e = 0.10 is strictly lower for the candidate, and
2. at e = 0.05 and e = 0.20 it is not higher, and
3. the format violation rate rises by at most 1 percentage point.
"""

from __future__ import annotations

import json
from decimal import Decimal
from pathlib import Path

from labelhub_evals import calibrate

PRIMARY_E = Decimal("0.10")
GUARD_ES = (Decimal("0.05"), Decimal("0.20"))
DEFAULT_BUDGET = Decimal("0.25")
MAX_FORMAT_RISE = Decimal("0.01")


class GateError(ValueError):
    pass


def _card(run_dir: Path) -> dict:
    return json.loads((run_dir / "scorecard.json").read_text(encoding="utf-8"))


def _held(run_dir: Path, budget: Decimal) -> dict:
    rows = calibrate.load(run_dir)
    with_loop = any("loop_outcome" in r for r in rows)
    pols = list(calibrate.policies(with_loop))
    split, cache = calibrate.folds(rows), {}
    return {e: calibrate.held_out(split, pols, e, budget, cache) for e in (PRIMARY_E, *GUARD_ES)}


def gate(reference: Path, candidate: Path, budget: Decimal = DEFAULT_BUDGET) -> tuple[str, bool]:
    ref_card, cand_card = _card(reference), _card(candidate)
    ref_id, cand_id = ref_card["run"], cand_card["run"]
    if ref_id["golden"] != cand_id["golden"]:
        raise GateError("runs use different golden sets")
    if ref_id["model"] != cand_id["model"]:
        raise GateError(f"runs use different models ({ref_id['model']} vs {cand_id['model']}); H4 must be compared on the same model")
    if "precedents" not in cand_id or "precedents" in ref_id:
        raise GateError("candidate must be a precedent run and the reference must not be")
    if ref_id.get("loop") != cand_id.get("loop"):
        raise GateError("runs use different H2 loop settings")
    ref, cand = _held(reference, budget), _held(candidate, budget)
    if any(v is None for v in (*ref.values(), *cand.values())):
        raise GateError(f"no feasible policy under the {budget * 100:.0f}% budget in some fold")
    checks = []
    p_ok = cand[PRIMARY_E][1] < ref[PRIMARY_E][1]
    checks.append((f"Held-out bad exports / 1000 at e = {PRIMARY_E:.2f} strictly lower", ref[PRIMARY_E][1], cand[PRIMARY_E][1], p_ok))
    for e in GUARD_ES:
        checks.append((f"Held-out bad exports / 1000 at e = {e:.2f} not higher", ref[e][1], cand[e][1], cand[e][1] <= ref[e][1]))
    rf, cf = Decimal(ref_card["scorecard"]["format_violation_rate"]), Decimal(cand_card["scorecard"]["format_violation_rate"])
    checks.append(("Format violation rate rises ≤ 1 pp", f"{rf * 100:.2f}%", f"{cf * 100:.2f}%", cf - rf <= MAX_FORMAT_RISE))
    passed = all(c[3] for c in checks)
    rs, cs = ref_card["scorecard"], cand_card["scorecard"]
    pc = cand_id["precedents"]
    pct = lambda v: "n/a" if v is None else f"{Decimal(v) * 100:.2f}%"
    lines = [
        f"# H4 gate: `{candidate.name}` (precedents) vs H3 reference `{reference.name}`",
        "",
        "Generated by `python -m labelhub_evals gate-h4`; do not edit by hand. Replays recorded answers only.",
        "",
        f"- Model: `{cand_id['model']}` · golden `{cand_id['golden']['name']}` ({rs['items']} items)",
        f"- Candidate precedents: `{pc['version']}` top {pc['k']}, retrieval `{pc['retrieval_sha256'][:12]}` (pool: HelpSteer2 train)",
        f"- Method: ADR-020 §2 calibration, best policy under an escalation budget of ≤ {budget * 100:.0f}%, 2-fold held-out by item_id",
        f"- **Gate (ADR-021 §6): {'PASS' if passed else 'FAIL'}**",
        "",
        "| Check | H3 reference | H4 candidate | OK |",
        "|---|---|---|---|",
    ]
    lines += [f"| {name} | {r} | {c} | {'✅' if ok else '❌'} |" for name, r, c, ok in checks]
    lines += [
        "",
        "Held-out escalation rate at the picked policies (context, not gated):",
        "",
        "| e | H3 escalation | H4 escalation |",
        "|---|---|---|",
    ]
    lines += [f"| {e:.2f} | {ref[e][0]}% | {cand[e][0]}% |" for e in (GUARD_ES[0], PRIMARY_E, GUARD_ES[1])]
    lines += [
        "",
        "Single-call metrics at the default thresholds (context, not gated):",
        "",
        "| Metric | H3 reference | H4 candidate |",
        "|---|---|---|",
        f"| Auto-pass error rate | {pct(rs['auto_pass_error_rate'])} | {pct(cs['auto_pass_error_rate'])} |",
        f"| Manual-review rate | {pct(rs['manual_review_rate'])} | {pct(cs['manual_review_rate'])} |",
        f"| Cohen's κ on decided items | {rs['cohen_kappa_decided']} | {cs['cohen_kappa_decided']} |",
        f"| Tokens in / out | {rs['tokens']['input_total']} / {rs['tokens']['output_total']} | {cs['tokens']['input_total']} / {cs['tokens']['output_total']} |",
        "",
    ]
    return "\n".join(lines), passed
