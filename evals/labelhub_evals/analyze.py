"""Error analysis of one run against its golden set: where the model disagrees with humans, and how
moving the three-zone thresholds would trade coverage for error. Deterministic, so the report it
renders can be regenerated byte for byte from committed files.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from decimal import Decimal
from pathlib import Path

from labelhub_evals.golden import GoldenItem

PASS_SWEEP = ("0.70", "0.80", "0.85", "0.90", "0.95")
REJECT_SWEEP = ("0.05", "0.10", "0.20", "0.30")


def _pct(num: int, den: int) -> str:
    return "n/a" if den == 0 else f"{Decimal(num * 100) / Decimal(den):.1f}%"


def analyze(items: list[GoldenItem], results: list[dict]) -> dict:
    by_id = {i.item_id: i for i in items}
    missing = [r["item_id"] for r in results if r["item_id"] not in by_id]
    if missing:
        raise ValueError(f"{len(missing)} results are not in this golden set; wrong --golden?")

    def cell(r):
        a = by_id[r["item_id"]].attributes
        return (a["helpfulness"], a["correctness"])

    grid: dict[str, dict] = {"pass": defaultdict(Counter), "reject": defaultdict(Counter)}
    for r in results:
        grid[r["truth"]][cell(r)][r["route"]] += 1

    scored = [r for r in results if r["score"] is not None]
    pass_sweep = []
    for t in PASS_SWEEP:
        zone = [r for r in scored if Decimal(r["score"]) >= Decimal(t)]
        pass_sweep.append({"threshold": t, "items": len(zone), "error": _pct(sum(r["truth"] == "reject" for r in zone), len(zone))})
    reject_sweep = []
    for t in REJECT_SWEEP:
        zone = [r for r in scored if Decimal(r["score"]) <= Decimal(t)]
        reject_sweep.append({"threshold": t, "items": len(zone), "error": _pct(sum(r["truth"] == "pass" for r in zone), len(zone))})

    suggestions = Counter(r["model_suggestion"] or "none" for r in results)
    truth = Counter(r["truth"] for r in results)
    return {"grid": grid, "pass_sweep": pass_sweep, "reject_sweep": reject_sweep, "suggestions": suggestions, "truth": truth, "n": len(results)}


def render(run_id: str, a: dict) -> str:
    lines = [f"# Error analysis for run `{run_id}`", "", "Generated by `python -m labelhub_evals analyze`; do not edit by hand.", ""]
    lines += ["## Model verdicts vs. human truth", "", "| | pass | reject | manual_review | none (format violation) |", "|---|---|---|---|---|"]
    s = a["suggestions"]
    lines.append(f"| Model `overallSuggestion` | {s['pass']} | {s['reject']} | {s['manual_review']} | {s['none']} |")
    lines.append(f"| Human truth | {a['truth']['pass']} | {a['truth']['reject']} | – | – |")
    for truth, title in (("pass", "Truth = pass: routing by (helpfulness, correctness)"), ("reject", "Truth = reject: routing by (helpfulness, correctness)")):
        lines += ["", f"## {title}", "", "| (h, c) | items | → pass | → manual | → reject | wrong-zone rate |", "|---|---|---|---|---|---|"]
        for key in sorted(a["grid"][truth]):
            c = a["grid"][truth][key]
            n = sum(c.values())
            wrong = c["reject"] if truth == "pass" else c["pass"]
            lines.append(f"| {key} | {n} | {c['pass']} | {c['manual_review']} | {c['reject']} | {_pct(wrong, n)} |")
    lines += ["", "## Threshold sweep (same recordings, no new calls)", "", "| auto-pass if score ≥ | items | auto-pass error |", "|---|---|---|"]
    lines += [f"| {r['threshold']} | {r['items']} | {r['error']} |" for r in a["pass_sweep"]]
    lines += ["", "| auto-reject if score ≤ | items | auto-reject error |", "|---|---|---|"]
    lines += [f"| {r['threshold']} | {r['items']} | {r['error']} |" for r in a["reject_sweep"]]
    return "\n".join(lines) + "\n"


def run_analysis(run_dir: Path, items: list[GoldenItem]) -> str:
    results = [json.loads(line) for line in (run_dir / "results.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
    return render(run_dir.name, analyze(items, results))
